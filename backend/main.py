def get_claude_client() -> Anthropic:
    """
    Create the Anthropic client using the API key
    from .env.
    """

    api_key = os.getenv(
        "ANTHROPIC_API_KEY"
    )

    if not api_key:
        raise RuntimeError(
            "ANTHROPIC_API_KEY is missing "
            "from the .env file"
        )

    return Anthropic(
        api_key=api_key
    )


# =========================================================
# GENERATE QUIZ QUESTIONS WITH AI
# =========================================================

def generate_quiz_questions(
    chunks: list[Chunk],
    num_questions: int,
    question_type: str,
) -> list[dict]:
    """
    Generate quiz questions using Claude.

    Claude receives only the document chunks.
    Therefore the questions are generated from
    the uploaded document.
    """

    if not chunks:
        raise ValueError(
            "The document has no chunks."
        )

    if num_questions < 1:
        raise ValueError(
            "num_questions must be at least 1"
        )

    if num_questions > 50:
        raise ValueError(
            "num_questions cannot exceed 50"
        )

    if question_type != "multiple_choice":
        raise ValueError(
            "Currently only multiple_choice "
            "questions are supported."
        )

    # -----------------------------------------------------
    # Build document context
    # -----------------------------------------------------

    context_parts = []

    for chunk in chunks:

        context_parts.append(
            f"""
PAGE: {chunk.page_number}

CONTENT:
{chunk.content}
""".strip()
        )

    context = "\n\n----------------\n\n".join(
        context_parts
    )

    # -----------------------------------------------------
    # Get model
    # -----------------------------------------------------

    claude_model = os.getenv(
        "CLAUDE_MODEL"
    )

    if not claude_model:
        raise RuntimeError(
            "CLAUDE_MODEL is missing "
            "from the .env file"
        )

    # -----------------------------------------------------
    # Prompt
    # -----------------------------------------------------

    prompt = f"""
You are the quiz-generation AI for StudyMate.

Create exactly {num_questions}
multiple-choice questions using ONLY the
document content provided below.

Do not use outside knowledge.

Each question must have:

- question_text
- question_type
- options
- correct_answer
- explanation
- source_page

Rules:

1. question_type must be "multiple_choice".
2. options must contain exactly four choices:
   A, B, C, D.
3. correct_answer must be exactly one of:
   A, B, C, D.
4. The correct answer must be supported by the document.
5. source_page must be the page where the information
   used to create the question appears.
6. explanation must explain why the correct answer
   is correct using the document.
7. Do not invent information.
8. Return ONLY valid JSON.
9. Do not use Markdown.
10. Return a JSON array.

Expected format:

[
  {{
    "question_text": "What is ...?",
    "question_type": "multiple_choice",
    "options": {{
      "A": "...",
      "B": "...",
      "C": "...",
      "D": "..."
    }},
    "correct_answer": "A",
    "explanation": "...",
    "source_page": 8
  }}
]

DOCUMENT:

{context}
""".strip()

    # -----------------------------------------------------
    # Call Claude
    # -----------------------------------------------------

    client = get_claude_client()

    try:

        response = client.messages.create(
            model=claude_model,
            max_tokens=6000,
            temperature=0,
            messages=[
                {
                    "role": "user",
                    "content": prompt,
                }
            ],
        )

    except RateLimitError as error:

        raise RuntimeError(
            "The AI service rate limit was reached."
        ) from error

    except APITimeoutError as error:

        raise RuntimeError(
            "The AI service took too long to respond."
        ) from error

    except APIConnectionError as error:

        raise RuntimeError(
            "Could not connect to the AI service."
        ) from error

    except APIStatusError as error:

        raise RuntimeError(
            f"The AI service returned an error: {error}"
        ) from error

    # -----------------------------------------------------
    # Extract response text
    # -----------------------------------------------------

    text_parts = [
        block.text
        for block in response.content
        if block.type == "text"
    ]

    response_text = "\n".join(
        text_parts
    ).strip()

    if not response_text:
        raise RuntimeError(
            "Claude returned an empty quiz response."
        )

    # -----------------------------------------------------
    # Parse JSON
    # -----------------------------------------------------

    try:

        questions = json.loads(
            response_text
        )

    except json.JSONDecodeError as error:

        raise RuntimeError(
            "Claude returned invalid JSON "
            "while generating the quiz."
        ) from error

    if not isinstance(
        questions,
        list,
    ):
        raise RuntimeError(
            "Claude quiz response must be a JSON array."
        )

    # -----------------------------------------------------
    # Validate generated questions
    # -----------------------------------------------------

    validated_questions = []

    for question in questions:

        if not isinstance(
            question,
            dict,
        ):
            continue

        required_fields = [
            "question_text",
            "question_type",
            "options",
            "correct_answer",
            "explanation",
            "source_page",
        ]

        if not all(
            field in question
            for field in required_fields
        ):
            continue

        options = question["options"]

        if not isinstance(
            options,
            dict,
        ):
            continue

        required_options = {
            "A",
            "B",
            "C",
            "D",
        }

        if set(options.keys()) != required_options:
            continue

        correct_answer = str(
            question["correct_answer"]
        ).upper()

        if correct_answer not in {
            "A",
            "B",
            "C",
            "D",
        }:
            continue

        validated_questions.append(
            {
                "question_text": str(
                    question["question_text"]
                ).strip(),

                "question_type": "multiple_choice",

                "options": options,

                "correct_answer": correct_answer,

                "explanation": str(
                    question["explanation"]
                ).strip(),

                "source_page": question[
                    "source_page"
                ],
            }
        )

    if len(validated_questions) != num_questions:
        raise RuntimeError(
            f"Claude generated {len(validated_questions)} valid questions, "
            f"but {num_questions} questions were requested."
        )

    return validated_questions



