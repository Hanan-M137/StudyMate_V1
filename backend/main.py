@app.post(
    "/quizzes/{quiz_id}/attempts"
)
def submit_quiz_attempt(
    quiz_id: UUID,
    attempt_data: QuizAttemptRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """
    Submit answers and calculate the final score.

    Student answers are compared directly with
    the correct answers stored in QuizQuestion.
    """

    # -----------------------------------------------------
    # Find quiz
    # -----------------------------------------------------

    quiz = (
        db.query(Quiz)
        .filter(
            Quiz.id == quiz_id,
            Quiz.user_id == current_user.id,
        )
        .first()
    )

    if not quiz:

        raise HTTPException(
            status_code=404,
            detail="Quiz not found",
        )

    # -----------------------------------------------------
    # Get questions
    # -----------------------------------------------------

    questions = (
        db.query(QuizQuestion)
        .filter(
            QuizQuestion.quiz_id == quiz.id
        )
        .all()
    )

    if not questions:

        raise HTTPException(
            status_code=400,
            detail="This quiz has no questions.",
        )

    # -----------------------------------------------------
    # Validate answers
    # -----------------------------------------------------

    submitted_answers = (
        attempt_data.answers
    )

    score = 0
    total_questions = len(questions)

    results = []

    # -----------------------------------------------------
    # Compare answers
    # -----------------------------------------------------

    for question in questions:

        question_id = str(
            question.id
        )

        student_answer = submitted_answers.get(
            question_id
        )

        if student_answer is not None:

            student_answer = str(
                student_answer
            ).strip().upper()

        correct_answer = (
            str(
                question.correct_answer
            )
            .strip()
            .upper()
        )

        is_correct = (
            student_answer
            == correct_answer
        )

        if is_correct:
            score += 1

        results.append(
            {
                "question_id": question_id,
                "student_answer": student_answer,
                "correct": is_correct,
            }
        )

    # -----------------------------------------------------
    # Calculate percentage
    # -----------------------------------------------------

    percentage = round(
        (score / total_questions) * 100,
        2,
    )

    # -----------------------------------------------------
    # Save attempt
    # -----------------------------------------------------

    attempt = QuizAttempt(
        quiz_id=quiz.id,
        user_id=current_user.id,
        score=score,
        answers=submitted_answers,
    )

    db.add(attempt)
    db.commit()
    db.refresh(attempt)

    # -----------------------------------------------------
    # Return final result
    # -----------------------------------------------------

    return {
        "message": "Quiz attempt submitted successfully",

        "attempt_id": str(
            attempt.id
        ),

        "score": score,

        "total_questions": total_questions,

        "percentage": percentage,

        "correct_answers": score,

        "wrong_answers": (
            total_questions - score
        ),

        "results": results,
    }