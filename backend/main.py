@app.post("/quizzes")
def create_quiz(
    quiz_data: QuizCreateRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """
    Create an AI-generated quiz.

    The API endpoint is responsible for:

        1. Validating the document.
        2. Creating the Quiz record.
        3. Delegating AI quiz generation to ai.service.

    The actual AI generation logic is implemented
    in ai/service.py.
    """

    # -----------------------------------------------------
    # Validate document ownership
    # -----------------------------------------------------

    document = (
        db.query(Document)
        .filter(
            Document.id == quiz_data.document_id,
            Document.user_id == current_user.id,
        )
        .first()
    )

    if not document:

        raise HTTPException(
            status_code=404,
            detail="Document not found",
        )

    # -----------------------------------------------------
    # Document must be ready
    # -----------------------------------------------------

    if document.status != "ready":

        raise HTTPException(
            status_code=400,
            detail=(
                f"Document is not ready. "
                f"Current status: {document.status}"
            ),
        )

    # -----------------------------------------------------
    # Validate number of questions
    # -----------------------------------------------------

    if quiz_data.num_questions < 1:

        raise HTTPException(
            status_code=400,
            detail="num_questions must be at least 1",
        )

    if quiz_data.num_questions > 50:

        raise HTTPException(
            status_code=400,
            detail="num_questions cannot exceed 50",
        )

    # -----------------------------------------------------
    # Create Quiz record
    # -----------------------------------------------------

    quiz = Quiz(
        user_id=current_user.id,
        document_id=document.id,
        title=quiz_data.title,
    )

    db.add(quiz)
    db.flush()

    # -----------------------------------------------------
    # Generate questions through AI service
    # -----------------------------------------------------

    try:

        generated_questions = generate_quiz(
            db=db,
            quiz=quiz,
            question_count=quiz_data.num_questions,
        )

    except ValueError as error:

        db.rollback()

        raise HTTPException(
            status_code=400,
            detail=str(error),
        )

    except RuntimeError as error:

        db.rollback()

        raise HTTPException(
            status_code=503,
            detail=str(error),
        )

    except Exception as error:

        db.rollback()

        raise HTTPException(
            status_code=500,
            detail=(
                "An error occurred while generating "
                "the quiz."
            ),
        ) from error

    # -----------------------------------------------------
    # Return result
    # -----------------------------------------------------

    return {
        "message": "Quiz created successfully",
        "quiz_id": str(quiz.id),
        "questions_count": len(
            generated_questions
        ),
    }


