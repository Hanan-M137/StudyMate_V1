@app.post("/quizzes")
def create_quiz(
    quiz_data: QuizCreateRequest,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """
    Create an AI-generated quiz.

    Flow:

        Document
            ↓
        Chunks
            ↓
        Claude
            ↓
        Questions
            ↓
        QuizQuestion records
    """

    # -----------------------------------------------------
    # Validate document ownership
    # -----------------------------------------------------

    document = (
        db.query(Document)
        .filter(
            Document.id == quiz_data.document_id,
            Document.user_id == current_user.id,
        )
        .first()
    )

    if not document:

        raise HTTPException(
            status_code=404,
            detail="Document not found",
        )

    # -----------------------------------------------------
    # Document must be ready
    # -----------------------------------------------------

    if document.status != "ready":

        raise HTTPException(
            status_code=400,
            detail=(
                f"Document is not ready. "
                f"Current status: {document.status}"
            ),
        )

    # -----------------------------------------------------
    # Get document chunks
    # -----------------------------------------------------

    chunks = (
        db.query(Chunk)
        .filter(
            Chunk.document_id == document.id
        )
        .order_by(
            Chunk.chunk_index
        )
        .all()
    )

    if not chunks:

        raise HTTPException(
            status_code=400,
            detail=(
                "No chunks were found for this document."
            ),
        )

    # -----------------------------------------------------
    # Generate questions using Claude
    # -----------------------------------------------------

    try:

        generated_questions = (
            generate_quiz_questions(
                chunks=chunks,
                num_questions=quiz_data.num_questions,
                question_type=quiz_data.question_type,
            )
        )

    except ValueError as error:

        raise HTTPException(
            status_code=400,
            detail=str(error),
        )

    except RuntimeError as error:

        raise HTTPException(
            status_code=503,
            detail=str(error),
        )

    except Exception as error:

        raise HTTPException(
            status_code=500,
            detail=(
                "An error occurred while generating "
                "the quiz."
            ),
        ) from error

    # -----------------------------------------------------
    # Create Quiz
    # -----------------------------------------------------

    quiz = Quiz(
        user_id=current_user.id,
        document_id=document.id,
        title=quiz_data.title,
    )

    db.add(quiz)
    db.flush()

    # -----------------------------------------------------
    # Create QuizQuestion records
    # -----------------------------------------------------

    for generated_question in generated_questions:

        question = QuizQuestion(
            quiz_id=quiz.id,
            question_text=(
                generated_question[
                    "question_text"
                ]
            ),
            question_type=(
                generated_question[
                    "question_type"
                ]
            ),
            options=(
                generated_question[
                    "options"
                ]
            ),
            correct_answer=(
                generated_question[
                    "correct_answer"
                ]
            ),
            explanation=(
                generated_question[
                    "explanation"
                ]
            ),
            source_page=(
                generated_question[
                    "source_page"
                ]
            ),
        )

        db.add(question)

    # -----------------------------------------------------
    # Commit everything
    # -----------------------------------------------------

    db.commit()
    db.refresh(quiz)

    return {
        "message": "Quiz created successfully",
        "quiz_id": str(quiz.id),
        "questions_count": len(
            generated_questions
        ),
    }


